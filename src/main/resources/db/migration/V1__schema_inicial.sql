-- ---------------------------------------------------------------------
-- Dev 1 — Miguel (usuario)
-- ---------------------------------------------------------------------
CREATE TABLE empresa (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                VARCHAR(20)  NOT NULL CHECK (tipo IN ('GERADORA', 'COLETORA')),
    razao_social        VARCHAR(150) NOT NULL,
    cnpj                VARCHAR(14)  NOT NULL UNIQUE,          -- só dígitos
    telefone            VARCHAR(20),
    endereco            VARCHAR(200),
    cidade              VARCHAR(100) NOT NULL,
    uf                  CHAR(2)      NOT NULL,
    latitude            DOUBLE PRECISION,
    longitude           DOUBLE PRECISION,
    raio_atendimento_km INTEGER CHECK (raio_atendimento_km > 0), -- só coletora
    criado_em           TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT       REFERENCES empresa (id),           -- NULL para ADMIN
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,                          -- BCrypt
    perfil     VARCHAR(20)  NOT NULL CHECK (perfil IN ('GERADORA', 'COLETORA', 'ADMIN')),
    ativo      BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Dev 2 — Felipe (homologacao)
-- ---------------------------------------------------------------------
CREATE TABLE homologacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    BIGINT      NOT NULL UNIQUE REFERENCES empresa (id),
    status        VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
                  CHECK (status IN ('PENDENTE', 'EM_ANALISE', 'APROVADA', 'REPROVADA', 'SUSPENSA')),
    motivo        VARCHAR(500),
    analisado_por BIGINT      REFERENCES usuario (id),
    analisado_em  TIMESTAMPTZ,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE documento_homologacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    homologacao_id BIGINT       NOT NULL REFERENCES homologacao (id),
    tipo           VARCHAR(30)  NOT NULL
                   CHECK (tipo IN ('LICENCA_AMBIENTAL', 'CADASTRO_IBAMA', 'MTR', 'ISO_27001', 'TISAX',
                                   'LAUDO_IEC_21964', 'OUTRO')),
    arquivo_ref    VARCHAR(300) NOT NULL,
    nome_original  VARCHAR(200),
    validade       DATE,
    enviado_em     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Dev 3 — Davi (solicitacao, roteamento)
-- ---------------------------------------------------------------------
CREATE TABLE solicitacao (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    geradora_id      BIGINT           NOT NULL REFERENCES empresa (id),
    descricao        VARCHAR(1000),
    peso_estimado_kg NUMERIC(10, 2)   NOT NULL CHECK (peso_estimado_kg > 0),
    contem_midias    BOOLEAN          NOT NULL DEFAULT FALSE,
    qtd_midias       INTEGER          NOT NULL DEFAULT 0 CHECK (qtd_midias >= 0),
    endereco         VARCHAR(200),
    cidade           VARCHAR(100)     NOT NULL,
    uf               CHAR(2)          NOT NULL,
    latitude         DOUBLE PRECISION NOT NULL,
    longitude        DOUBLE PRECISION NOT NULL,
    status           VARCHAR(20)      NOT NULL DEFAULT 'ABERTA'
                     CHECK (status IN ('ABERTA', 'ACEITA', 'AGENDADA', 'COLETADA', 'CONCLUIDA',
                                       'CANCELADA', 'EXPIRADA')),
    coletora_id      BIGINT           REFERENCES empresa (id),
    aceita_em        TIMESTAMPTZ,
    agendada_para    TIMESTAMPTZ,
    criada_em        TIMESTAMPTZ      NOT NULL DEFAULT now(),
    version          BIGINT           NOT NULL DEFAULT 0
);
CREATE INDEX ix_solicitacao_status ON solicitacao (status);
CREATE INDEX ix_solicitacao_geradora ON solicitacao (geradora_id);
CREATE INDEX ix_solicitacao_coletora ON solicitacao (coletora_id);

CREATE TABLE solicitacao_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT         NOT NULL REFERENCES solicitacao (id) ON DELETE CASCADE,
    tipo_residuo   VARCHAR(30)    NOT NULL
                   CHECK (tipo_residuo IN ('INFORMATICA', 'TELEFONIA', 'ELETRODOMESTICO',
                                           'MIDIA_ARMAZENAMENTO', 'BATERIA', 'OUTRO')),
    quantidade     INTEGER        NOT NULL CHECK (quantidade > 0),
    peso_kg        NUMERIC(10, 2)
);

CREATE TABLE alerta_solicitacao (
    solicitacao_id BIGINT        NOT NULL REFERENCES solicitacao (id),
    coletora_id    BIGINT        NOT NULL REFERENCES empresa (id),
    distancia_km   NUMERIC(8, 2) NOT NULL,
    enviado_em     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    PRIMARY KEY (solicitacao_id, coletora_id)
);

-- ---------------------------------------------------------------------
-- Dev 4 — Guilherme (rastreio, documento)
-- ---------------------------------------------------------------------
CREATE TABLE evento_rastreio (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT       NOT NULL REFERENCES solicitacao (id),
    tipo           VARCHAR(30)  NOT NULL
                   CHECK (tipo IN ('CRIADA', 'ALERTAS_ENVIADOS', 'ACEITA', 'AGENDADA', 'COLETADA',
                                   'MIDIAS_DESTRUIDAS', 'DESTINADA', 'CONCLUIDA', 'CANCELADA')),
    descricao      VARCHAR(500),
    peso_real_kg   NUMERIC(10, 2),
    evidencia_ref  VARCHAR(300),
    registrado_por BIGINT       REFERENCES usuario (id),     -- NULL = evento automático
    registrado_em  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_evento_rastreio_solicitacao ON evento_rastreio (solicitacao_id);

CREATE TABLE midia_destruida (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT       NOT NULL REFERENCES solicitacao (id),
    numero_serie   VARCHAR(100) NOT NULL,
    tipo           VARCHAR(10)  NOT NULL CHECK (tipo IN ('HDD', 'SSD', 'FITA', 'OUTRO')),
    metodo         VARCHAR(20)  NOT NULL CHECK (metodo IN ('TRITURACAO', 'DESMAGNETIZACAO')),
    nivel          VARCHAR(10)  NOT NULL,                     -- ex.: H-4, H-5 (DIN 66399 / IEC 21964)
    destruida_em   TIMESTAMPTZ  NOT NULL,
    UNIQUE (solicitacao_id, numero_serie)
);

CREATE TABLE documento_emitido (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id     BIGINT       NOT NULL REFERENCES solicitacao (id),
    tipo               VARCHAR(30)  NOT NULL
                       CHECK (tipo IN ('CDF', 'LAUDO_TECNICO', 'CERTIFICADO_DESTRUICAO')),
    numero             VARCHAR(40)  NOT NULL UNIQUE,
    arquivo_ref        VARCHAR(300) NOT NULL,
    hash_sha256        CHAR(64),
    codigo_verificacao VARCHAR(40)  UNIQUE,
    emitido_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (solicitacao_id, tipo)
);

-- ---------------------------------------------------------------------
-- Dev 5 — Rafael (notificacao, mapa, monetizacao)
-- ---------------------------------------------------------------------
CREATE TABLE notificacao (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT       REFERENCES empresa (id),          -- NULL = para os administradores
    tipo       VARCHAR(40)  NOT NULL,
    titulo     VARCHAR(150) NOT NULL,
    mensagem   VARCHAR(500),
    link       VARCHAR(300),
    lida       BOOLEAN      NOT NULL DEFAULT FALSE,
    criada_em  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_notificacao_empresa_lida ON notificacao (empresa_id, lida);

CREATE TABLE ponto_descarte (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(150)     NOT NULL,
    endereco      VARCHAR(200),
    cidade        VARCHAR(100)     NOT NULL,
    uf            CHAR(2)          NOT NULL,
    latitude      DOUBLE PRECISION NOT NULL,
    longitude     DOUBLE PRECISION NOT NULL,
    tipos_aceitos VARCHAR(300),
    horario       VARCHAR(150),
    ativo         BOOLEAN          NOT NULL DEFAULT TRUE
);

CREATE TABLE plano (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(60)    NOT NULL UNIQUE,
    valor_mensal NUMERIC(10, 2) NOT NULL CHECK (valor_mensal >= 0)
);

CREATE TABLE assinatura (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT      NOT NULL REFERENCES empresa (id),
    plano_id   BIGINT      NOT NULL REFERENCES plano (id),
    status     VARCHAR(20) NOT NULL CHECK (status IN ('ATIVA', 'CANCELADA')),
    inicio     DATE        NOT NULL
);

-- Quem paga: TAXA_MATCH e MENSALIDADE = coletora; TAXA_DOCUMENTO = geradora.
CREATE TABLE lancamento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT         NOT NULL REFERENCES empresa (id),
    tipo           VARCHAR(20)    NOT NULL CHECK (tipo IN ('MENSALIDADE', 'TAXA_MATCH', 'TAXA_DOCUMENTO')),
    solicitacao_id BIGINT         REFERENCES solicitacao (id),
    documento_id   BIGINT         REFERENCES documento_emitido (id),
    valor          NUMERIC(10, 2) NOT NULL,
    competencia    DATE           NOT NULL,                  -- primeiro dia do mês de referência
    criado_em      TIMESTAMPTZ    NOT NULL DEFAULT now()
);
-- Garante no banco que nenhum evento gera cobrança em dobro
CREATE UNIQUE INDEX ux_lancamento_match ON lancamento (solicitacao_id) WHERE tipo = 'TAXA_MATCH';
CREATE UNIQUE INDEX ux_lancamento_documento ON lancamento (documento_id) WHERE tipo = 'TAXA_DOCUMENTO';
