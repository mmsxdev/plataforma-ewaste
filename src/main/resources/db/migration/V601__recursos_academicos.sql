-- Recursos de Banco de Dados II. A migration V600 preserva dados anteriores;
-- estes objetos acrescentam consulta, regra, operação e auditoria demonstráveis.

CREATE VIEW vw_acompanhamento_solicitacao WITH (security_invoker = true) AS
SELECT s.id AS solicitacao_id, s.geradora_id, g.razao_social AS geradora_nome,
       s.coletora_id, c.razao_social AS coletora_nome,
       s.ponto_descarte_id, p.nome AS ponto_nome, s.status, s.criada_em,
       COALESCE(i.linhas, 0) AS linhas_itens,
       COALESCE(i.quantidade, 0) AS quantidade_total,
       COALESCE(d.quantidade, 0) AS documentos_emitidos, e.ultimo_evento_em
  FROM solicitacao s
  JOIN empresa g ON g.id = s.geradora_id
  LEFT JOIN empresa c ON c.id = s.coletora_id
  LEFT JOIN ponto_descarte p ON p.id = s.ponto_descarte_id
  LEFT JOIN LATERAL (
      SELECT count(*) AS linhas, sum(quantidade) AS quantidade
        FROM solicitacao_item WHERE solicitacao_id = s.id
  ) i ON true
  LEFT JOIN LATERAL (
      SELECT count(*) AS quantidade FROM documento_emitido WHERE solicitacao_id = s.id
  ) d ON true
  LEFT JOIN LATERAL (
      SELECT max(registrado_em) AS ultimo_evento_em FROM evento_rastreio WHERE solicitacao_id = s.id
  ) e ON true;

-- Valores aceitos são nomes do enum TipoResiduo, separados por vírgulas.
-- Lista vazia/NULL, categoria desconhecida e ponto inativo não aceitam material.
CREATE FUNCTION ponto_aceita_tipo(p_ponto_id BIGINT, p_tipo VARCHAR)
RETURNS BOOLEAN
LANGUAGE SQL STABLE
AS $function$
    SELECT EXISTS (
        SELECT 1 FROM ponto_descarte p
         WHERE p.id = p_ponto_id AND p.ativo
           AND upper(btrim(p_tipo)) = ANY (ARRAY[
               'INFORMATICA', 'TELEFONIA', 'ELETRODOMESTICO',
               'MIDIA_ARMAZENAMENTO', 'BATERIA', 'OUTRO'])
           AND upper(btrim(p_tipo)) = ANY (
               regexp_split_to_array(upper(btrim(COALESCE(p.tipos_aceitos, ''))), '\s*,\s*'))
    );
$function$;

-- INVOKER: não eleva os privilégios do usuário da aplicação. O serviço já
-- valida propriedade; aqui também conferimos o ator e protegemos SQL direto.
CREATE PROCEDURE registrar_destinacao_pi(
    p_solicitacao_id BIGINT, p_usuario_id BIGINT, p_descricao TEXT)
LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_status VARCHAR(20);
    v_coletora_id BIGINT;
BEGIN
    IF p_descricao IS NULL OR p_descricao ~ '^[[:space:]]*$' OR length(p_descricao) > 500 THEN
        RAISE EXCEPTION 'Descreva a destinação final.' USING ERRCODE = '22023';
    END IF;
    SELECT status, coletora_id INTO v_status, v_coletora_id
      FROM solicitacao WHERE id = p_solicitacao_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Coleta não encontrada.' USING ERRCODE = 'P0002';
    END IF;
    IF v_status <> 'COLETADA' THEN
        RAISE EXCEPTION 'Esta operação não está disponível no estado atual da coleta.'
            USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM usuario WHERE id = p_usuario_id AND ativo
          AND perfil = 'COLETORA' AND empresa_id = v_coletora_id
    ) THEN
        RAISE EXCEPTION 'Usuário não autorizado para esta coleta.' USING ERRCODE = '42501';
    END IF;
    IF EXISTS (
        SELECT 1 FROM evento_rastreio
         WHERE solicitacao_id = p_solicitacao_id AND tipo = 'DESTINADA'
    ) THEN
        RAISE EXCEPTION 'A destinação já foi registrada.' USING ERRCODE = '23514';
    END IF;
    INSERT INTO evento_rastreio (solicitacao_id, tipo, descricao, registrado_por)
    VALUES (p_solicitacao_id, 'DESTINADA', btrim(p_descricao), p_usuario_id);
END;
$procedure$;

-- Auditoria técnica de mudanças efetivas de estado; não duplica a linha do
-- tempo de negócio nem presume identidade humana a partir da conexão SQL.
CREATE TABLE solicitacao_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL REFERENCES solicitacao(id),
    status_anterior VARCHAR(20) NOT NULL,
    status_novo VARCHAR(20) NOT NULL,
    usuario_banco TEXT NOT NULL,
    transacao_id BIGINT NOT NULL,
    registrado_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX ix_solicitacao_auditoria_solicitacao
    ON solicitacao_auditoria (solicitacao_id, registrado_em);

CREATE FUNCTION auditar_status_solicitacao_pi()
RETURNS TRIGGER LANGUAGE plpgsql AS $trigger$
BEGIN
    INSERT INTO solicitacao_auditoria
        (solicitacao_id, status_anterior, status_novo, usuario_banco, transacao_id)
    VALUES (NEW.id, OLD.status, NEW.status, current_user, txid_current());
    RETURN NEW;
END;
$trigger$;

CREATE TRIGGER trg_auditar_status_solicitacao_pi
AFTER UPDATE OF status ON solicitacao
FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION auditar_status_solicitacao_pi();
